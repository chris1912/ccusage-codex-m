#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
script_src="$repo_root/ccusage_m_view.js"

if [[ ! -f "$script_src" ]]; then
  echo "ccusage_m_view.js not found at: $script_src" >&2
  exit 1
fi

# Resolve CODEX_HOME:
# - If set, use it
# - Else if ~/.codex exists, use it
# - Else default to ~/.codex and create it
codex_home="${CODEX_HOME:-}"
if [[ -z "$codex_home" ]]; then
  if [[ -n "${USERPROFILE:-}" ]] && command -v cygpath >/dev/null 2>&1; then
    codex_home="$(cygpath -u "$USERPROFILE")/.codex"
  else
    codex_home="$HOME/.codex"
  fi
fi
mkdir -p "$codex_home"

codex_home_for_node="$codex_home"
if command -v cygpath >/dev/null 2>&1; then
  codex_home_for_node="$(cygpath -m "$codex_home")"
fi

target="$codex_home/ccusage_m_view.js"
source_pointer="$codex_home/ccusage_m_view.repo"
if [[ -f "$target" ]]; then
  cp -f "$target" "$target.bak-$(date +%Y%m%d_%H%M%S)"
fi
if [[ -f "$source_pointer" ]]; then
  cp -f "$source_pointer" "$source_pointer.bak-$(date +%Y%m%d_%H%M%S)"
fi
repo_root_for_node="$repo_root"
if command -v cygpath >/dev/null 2>&1; then
  repo_root_for_node="$(cygpath -m "$repo_root")"
fi
# 只安装入口，实际逻辑始终从仓库源文件加载，避免 Git 更新后运行旧副本。
printf '%s\n' \
  "'use strict';" \
  "const fs = require('fs');" \
  "const path = require('path');" \
  "const pointer = path.join(__dirname, 'ccusage_m_view.repo');" \
  'const envRoot = process.env.CCUSAGE_CODEX_REPO;' \
  "const fileRoot = fs.existsSync(pointer) ? fs.readFileSync(pointer, 'utf8').trim() : '';" \
  "const repoRoot = [envRoot, fileRoot].find((root) => root && fs.existsSync(path.join(root, 'ccusage_m_view.js')));" \
  "if (!repoRoot) throw new Error('ccusage-codex-m source repository was not found. Re-run the installer.');" \
  "require(path.join(repoRoot, 'ccusage_m_view.js'));" > "$target"
printf '%s\n' "$repo_root_for_node" > "$source_pointer"

choose_rc() {
  if [[ -f "$HOME/.zshrc" ]]; then
    echo "$HOME/.zshrc"
    return
  fi
  echo "$HOME/.bashrc"
}

rc_file="$(choose_rc)"
mkdir -p "$(dirname "$rc_file")"
touch "$rc_file"
cp -f "$rc_file" "$rc_file.bak-$(date +%Y%m%d_%H%M%S)"

marker="ccusage-codex-m"
begin="# >>> $marker >>>"
end="# <<< $marker <<<"

block="$begin
# ccusage-codex-m command family (generated by ccusage-codex-m/scripts/install.sh)
export CODEX_HOME=\"$codex_home_for_node\"
export CCUSAGE_CODEX_REPO=\"$repo_root\"

ccusage-codex-m() { node \"$codex_home_for_node/ccusage_m_view.js\" daily \"\$@\"; }
ccusage-codex-monthly() { node \"$codex_home_for_node/ccusage_m_view.js\" monthly \"\$@\"; }
ccusage-codex-open() { node \"$codex_home_for_node/ccusage_m_view.js\" sessions \"\$@\"; }
$end"

if grep -qF "$begin" "$rc_file" && grep -qF "$end" "$rc_file"; then
  echo "Profile already contains $marker block: $rc_file"
  echo "Run with FORCE=1 to replace it."
  if [[ "${FORCE:-}" == "1" ]]; then
    tmp="$(mktemp)"
    # Replace existing block between begin/end (inclusive).
    awk -v b="$begin" -v e="$end" -v repl="$block" '
      BEGIN { inside_block=0 }
      $0==b { print repl; inside_block=1; next }
      $0==e { inside_block=0; next }
      inside_block==0 { print }
    ' "$rc_file" > "$tmp"
    mv "$tmp" "$rc_file"
    echo "Replaced $marker block in: $rc_file"
  fi
else
  printf "\n%s\n" "$block" >> "$rc_file"
  echo "Updated profile: $rc_file"
fi

echo "Installed launcher: $target"
echo "Source:           $script_src"
echo "Source pointer:   $source_pointer"
echo "Next:"
echo "  1) source \"$rc_file\""
echo "  2) ccusage-codex-m"

